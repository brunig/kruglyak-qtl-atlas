def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def cell(v):
    if isinstance(v, float) and v.is_integer() and abs(v) < 1e15:
        v = int(v)
    s = str(v).replace("|", "\\|").replace("\n", " ")
    return s if len(s) <= 60 else s[:57] + "..."


def sheets_of(path):
    """Yield (sheet name, list of rows) for an .xls or .xlsx file."""
    if path.endswith(".xls"):
        import xlrd
        book = xlrd.open_workbook(path)
        for sh in book.sheets():
            yield sh.name, [sh.row_values(i) for i in range(sh.nrows)]
    else:
        import openpyxl
        book = openpyxl.load_workbook(path, read_only=True, data_only=True)
        for ws in book.worksheets:
            rows = [["" if v is None else v for v in r] for r in ws.iter_rows(values_only=True)]
            yield ws.title, rows


def main():
    files = sorted(os.listdir(RAW))
    man = ["file\tbytes\tsha256"]
    md = ["# Inventory: Bloom et al. 2019 (eLife 8:e49212) supplementary bundle", "",
          "Generated by `ingest/inventory.py` from `sources/bloom2019/raw/`, the unzipped",
          "`elife-49212-supp-v1.zip` (10,729,714 bytes). The files inside are named",
          "`elife_poa_e49212_*`, not `elife-49212-fig3-data1-v1.*` as the task brief anticipated;",
          "the mapping is one to one by caption (Figure 3-source data 1 = `elife_poa_e49212_Figure_3_source_data_1.xls`, and so on).",
          "Checksums are in `MANIFEST.tsv`.", "",
          "Spreadsheets are summarised sheet by sheet: dimensions (rows x columns, including the",
          "header row), column names, and the first three data rows. Values over 60 characters are cut.", ""]
    md.append("| file | type | bytes | role |")
    md.append("|---|---|---:|---|")
    for f in files:
        p = os.path.join(RAW, f)
        man.append(f"{f}\t{os.path.getsize(p)}\t{sha256(p)}")
        md.append(f"| `{f}` | {f.rsplit('.', 1)[1]} | {os.path.getsize(p):,} | {ROLE.get(f, '')} |")
    md.append("")
    for f in files:
        p = os.path.join(RAW, f)
        md.append(f"## `{f}`")
        md.append("")
        md.append(ROLE.get(f, ""))
        md.append("")
        if f.endswith((".xls", ".xlsx")):
            for name, rows in sheets_of(p):
                ncol = max((len(r) for r in rows), default=0)
                # trim trailing empty columns for display
                used = 0
                for r in rows:
                    for j, v in enumerate(r):
                        if v not in ("", None):
                            used = max(used, j + 1)
                hr = HEADER_ROW.get((f, name), 0)
                md.append(f"### Sheet `{name}`: {len(rows)} rows x {ncol} columns ({used} used)")
                md.append("")
                if hr:
                    md.append(f"Row {hr} (1-based) is a group banner: " +
                              "; ".join(f"col {j + 1}: {cell(v)}" for j, v in enumerate(rows[0]) if v not in ("", None)) +
                              f". Column names are on row {hr + 1}.")
                    md.append("")
                hrow = list(rows[hr]) + [""] * (used - len(rows[hr]))
                head = [cell(v) if v not in ("", None) else f"(col {j + 1}, unnamed)" for j, v in enumerate(hrow[:used])]
                md.append("Columns: " + ", ".join(f"`{h}`" for h in head))
                md.append("")
                md.append("| " + " | ".join(head) + " |")
                md.append("|" + "---|" * len(head))
                for r in rows[hr + 1:hr + 4]:
                    r = list(r) + [""] * (used - len(r))
                    md.append("| " + " | ".join(cell(v) for v in r[:used]) + " |")
                md.append("")
                if f.endswith("Figure_1_source_data_1.xls") and name == "Phenotypes":
                    md.append("This sheet holds two stacked tables: compound stock recipes (rows 1-17) and, from row 21, "
                              "a condition table (22 conditions) followed by carbon-source and pH sections. "
                              "It has no trait identifiers; traits are named in the QTL tables.")
                    md.append("")
        elif f.endswith(".pdf"):
            import pdfplumber
            with pdfplumber.open(p) as pdf:
                first = [(pg.extract_text() or "").split("\n")[0] for pg in pdf.pages]
                md.append(f"{len(pdf.pages)} page(s). First text line of the first pages: " +
                          "; ".join(f"p{i + 1} `{cell(t)}`" for i, t in enumerate(first[:4])))
                md.append("")
        elif f.endswith(".docx"):
            with zipfile.ZipFile(p) as z:
                md.append(f"Word document, {len(z.namelist())} parts in the archive. Not used by the atlas.")
                md.append("")
    md.append("## Not in the bundle")
    md.append("")
    md.append("- No column for the parents' ecological origins (Figure 1-source data 1 gives strain names and "
              "the Peter et al. 2018 isolate IDs only). See OPEN_QUESTIONS.md.")
    md.append("- No genotype matrix, variant list, or parental genotypes; the 298,979-variant count cannot be checked from these files.")
    md.append("- No LOD, p or q value for joint-model QTL, and no interval for them: the joint tables give a lead variant only.")
    md.append("- No list of the 26 experimentally validated genes; see `previously_identified.tsv` for what the analysis code records.")
    md.append("")
    with open(os.path.join(OUT, "INVENTORY.md"), "w") as fh:
        fh.write("\n".join(md))
    with open(os.path.join(OUT, "MANIFEST.tsv"), "w") as fh:
        fh.write("\n".join(man) + "\n")
    print("wrote INVENTORY.md and MANIFEST.tsv for", len(files), "files", file=sys.stderr)


if __name__ == "__main__":
    main()
