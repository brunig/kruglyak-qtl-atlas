def sheet_md(f, name, rows, hr):
    md = []
    ncol = max((len(r) for r in rows), default=0)
    used = 0
    for r in rows:
        for j, v in enumerate(r):
            if v not in ("", None):
                used = max(used, j + 1)
    md.append(f"### Sheet `{name}`: {len(rows)} rows x {ncol} columns ({used} used)")
    md.append("")
    if not rows or not used:
        return md + ["(empty)", ""]
    if hr:
        md.append(f"Rows 1-{hr} (1-based) are banners or titles: " +
                  "; ".join(f"row {i + 1}: " + " | ".join(cell(v) for v in rows[i] if v not in ("", None)) for i in range(hr)) +
                  f". Column names are on row {hr + 1}.")
        md.append("")
    hrow = list(rows[hr]) + [""] * (used - len(rows[hr]))
    head = [cell(v) if v not in ("", None) else f"(col {j + 1}, unnamed)" for j, v in enumerate(hrow[:used])]
    md.append("Columns: " + ", ".join(f"`{h}`" for h in head))
    md.append("")
    md.append("| " + " | ".join(head) + " |")
    md.append("|" + "---|" * len(head))
    for r in rows[hr + 1:hr + 4]:
        r = list(r) + [""] * (used - len(r))
        md.append("| " + " | ".join(cell(v) for v in r[:used]) + " |")
    md.append("")
    if (f, name) in NOTES:
        md += [NOTES[(f, name)], ""]
    return md


def run(ds):
    RAW = os.path.join(ROOT, "sources", ds, "raw")
    OUT = os.path.join(ROOT, "sources", ds)
    M = meta_for(ds)
    files = sorted(os.listdir(RAW))
    man = ["file\tbytes\tsha256"]
    md = ["# " + M["title"], ""] + list(M["intro"]) + ["",
          "Spreadsheets and text tables are summarised sheet by sheet: dimensions (rows x columns, including the",
          "header row), column names, and the first three data rows. Values over 60 characters are cut.", ""]
    md.append("| file | type | bytes | role |")
    md.append("|---|---|---:|---|")
    for f in files:
        p = os.path.join(RAW, f)
        man.append(f"{f}\t{os.path.getsize(p)}\t{sha256(p)}")
        md.append(f"| `{f}` | {f.rsplit('.', 1)[-1]} | {os.path.getsize(p):,} | {M['roles'].get(f, '')} |")
    md.append("")
    for f in files:
        p = os.path.join(RAW, f)
        md += [f"## `{f}`", "", M["roles"].get(f, ""), ""]
        if f.endswith((".xls", ".xlsx")):
            for name, rows in sheets_of(p):
                md += sheet_md(f, name, rows, M["header_rows"].get(f + "|" + name, 0))
        elif f.endswith((".txt", ".tsv", ".csv")):
            with open(p, encoding="utf-8", errors="replace") as fh:
                lines = fh.read().splitlines()
            sep = "," if f.endswith(".csv") else "\t"
            rows = [l.split(sep) for l in lines]
            if max((len(r) for r in rows), default=0) > 1:
                md += sheet_md(f, "(text table)", rows, M["header_rows"].get(f + "|", 0))
            else:
                md += [f"Plain text, {len(lines)} lines. First lines:", "", "```"] + [l[:120] for l in lines[:6]] + ["```", ""]
        elif f.endswith(".pdf"):
            import pdfplumber
            with pdfplumber.open(p) as pdf:
                first = [(pg.extract_text() or "").split("\n")[0] for pg in pdf.pages]
                md.append(f"{len(pdf.pages)} page(s). First text line of the first pages: " +
                          "; ".join(f"p{i + 1} `{cell(t)}`" for i, t in enumerate(first[:4])))
                md.append("")
        elif f.endswith(".docx"):
            with zipfile.ZipFile(p) as z:
                md += [f"Word document, {len(z.namelist())} parts in the archive.", ""]
        elif f.endswith(".doc"):
            md += ["Legacy Word document (figure or text supplement); not parsed by the atlas.", ""]
        else:
            md += ["Image or binary figure file; not parsed by the atlas.", ""]
    if M["missing"]:
        md += ["## Not in the bundle", ""] + ["- " + l for l in M["missing"]] + [""]
    with open(os.path.join(OUT, "INVENTORY.md"), "w") as fh:
        fh.write("\n".join(md))
    with open(os.path.join(OUT, "MANIFEST.tsv"), "w") as fh:
        fh.write("\n".join(man) + "\n")
    print(f"{ds}: wrote INVENTORY.md and MANIFEST.tsv for {len(files)} files", file=sys.stderr)


def main():
    names = sys.argv[1:] or sorted(d for d in os.listdir(os.path.join(ROOT, "sources"))
                                   if os.path.isdir(os.path.join(ROOT, "sources", d, "raw")))
    for ds in names:
        run(ds)


if __name__ == "__main__":
    main()
