def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def cell(v):
    if isinstance(v, float) and v.is_integer() and abs(v) < 1e15:
        v = int(v)
    s = str(v).replace("|", "\\|").replace("\n", " ")
    return s if len(s) <= 60 else s[:57] + "..."


def sheets_of(path):
    """Yield (sheet name, list of rows) for an .xls or .xlsx file."""
    if path.endswith(".xls"):
        import xlrd
        book = xlrd.open_workbook(path)
        for sh in book.sheets():
            yield sh.name, [sh.row_values(i) for i in range(sh.nrows)]
    else:
        import openpyxl
        book = openpyxl.load_workbook(path, read_only=True, data_only=True)
        for ws in book.worksheets:
            rows = [["" if v is None else v for v in r] for r in ws.iter_rows(values_only=True)]
            yield ws.title, rows


def meta_for(ds):
    if ds == "bloom2019":
        return {"title": "Inventory: Bloom et al. 2019 (eLife 8:e49212) supplementary bundle", "intro": BLOOM_INTRO,
                "roles": ROLE, "header_rows": {f + "|" + sh: r for (f, sh), r in HEADER_ROW.items()}, "missing": BLOOM_MISSING}
    p = os.path.join(ROOT, "sources", ds, "inventory_meta.json")
    m = json.load(open(p)) if os.path.exists(p) else {}
    m.setdefault("title", "Inventory: " + ds); m.setdefault("intro", []); m.setdefault("roles", {})
    m.setdefault("header_rows", {}); m.setdefault("missing", [])
    return m


